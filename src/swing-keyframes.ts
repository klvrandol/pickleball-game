export function swingProfile(hand: SwingHand, kind: SwingKind) { return SWING_PROFILES.find(p => p.hand === hand && p.kind === kind)!; }
export function sampleSwingKey(profile: SwingProfile, time: number): SwingKey {
  const keys = profile.keys; const t = Math.max(0, Math.min(1, time));
  const next = keys.findIndex(key => key.time >= t);
  if (next <= 0) return keys[0];
  const a = keys[next - 1], b = keys[next], previous = keys[Math.max(0, next - 2)], following = keys[Math.min(keys.length - 1, next + 1)];
  const span = b.time - a.time, u = (t - a.time) / span;
  const mix = (get: (key: SwingKey) => number) => {
    const start = get(a), end = get(b);
    const m0 = a.time === 0 ? 0 : (get(b) - get(previous)) / (b.time - previous.time);
    const m1 = b.time === 1 ? 0 : (get(following) - get(a)) / (following.time - a.time);
    return (2*u**3-3*u*u+1)*start + (u**3-2*u*u+u)*span*m0 + (-2*u**3+3*u*u)*end + (u**3-u*u)*span*m1;
  };
  const v = (name: 'paddle' | 'chain' | 'wrist' | 'lower'): V3 => [0,1,2].map(i => mix(key => key[name][i])) as V3;
  return { time:t, paddle:v('paddle'), chain:v('chain'), wrist:v('wrist'), lower:v('lower'), support:mix(key => key.support), heel:mix(key => key.heel) };
}
